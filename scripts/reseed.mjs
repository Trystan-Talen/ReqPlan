// 任务状态按「截止日相对今天」推导，让种子数据天然带上 待开始/开发中/已完成 的混合分布。
// 若把基线放在今天之后，全库任务都会是「待开始」，进度条、里程碑、流转演示全都看不出效果。
const TODAY = '2026-09-12';
// 本周一。只有拿它去比才对：任务起止都落在周一/周五，直接拿 UTC 当天的日期比，同周任务永远进不了「开发中」
const THIS_MON = (() => {
  const d = new Date(Date.parse(TODAY));
  return new Date(d.getTime() - ((d.getUTCDay() + 6) % 7) * 864e5).toISOString().slice(0, 10);
})();
// 判断要用任务自己的起止周：只看到期周的话，一条跨周任务会在开工前就被标成「开发中」
const taskStatus = (ws, we) => {
  if (FRI(we) < TODAY) return '已完成';
  return MON(ws) <= THIS_MON ? '开发中' : '待开始';
};

// 需求状态：有任务的一律从任务倒推，避免出现「需求开发中、任务全已完成」这种一眼假的数据。
// 全做完的进「已完成」，开了工的进「开发中」，一条都没开工的必然已经拆过任务、也排过期，进「已排期」。
// 没有任务的需求还没走到拆分那一步，状态就是评审前的原样（源表里写的 未确定 / 待评审 / 已确定），
// 正好让状态机最前面那段在演示里有真实样本，而不是把「未确定」硬塞给一条已经排好期的需求。
const seedStatus = (ts, fallback) => {
  if (!ts.length) return fallback;
  const st = ts.map(([, , ws, we]) => taskStatus(ws, we));
  if (st.every((s) => s === '已完成')) return '已完成';
  return st.some((s) => s !== '待开始') ? '开发中' : '已排期';
};

